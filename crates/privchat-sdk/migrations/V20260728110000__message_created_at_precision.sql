-- 记录 created_at 的**精度**，因为归一之后数值上已经看不出来了。
--
-- wire 上两种都有：PushMessageRequest.timestamp 是 u32 秒，history/sync 是毫秒。
-- 适配器会把秒乘成毫秒，于是到了这一层，一个来自 push 的 1785148271000 和一个真
-- 实的毫秒值长得一模一样。此前靠 `created_at % 1000 <> 0` 之类的数值形状去猜，那
-- 是猜不准的：真实发送时间正好落在整秒上完全可能。
--
-- 合并规则（两端一致）：
--   * 本地还没有值 → 采用新值；
--   * 高精度覆盖低精度；
--   * 低精度**永不**覆盖高精度（跨秒也不行——「最后到达者获胜」是最没有权威性的
--     规则）；
--   * 同精度但值不同 = 某一端数据坏了，普通 replay 不覆盖，只打点；要改只能走
--     显式的定向 repair。
--
-- 1 = 毫秒，0 = 秒。存量行按毫秒处理：绝大多数写入路径本来就是毫秒，而把毫秒误标
-- 成秒会让它被任何来源覆盖，是更危险的方向。
ALTER TABLE message ADD COLUMN created_at_precision INTEGER NOT NULL DEFAULT 1;
